/**
 * Writes the Biochemistry coverage checklist and audit report.
 * Usage: npm run report:biochem
 */
import { writeFileSync } from 'node:fs';
import { BIOCHEMISTRY, BIOCHEMISTRY_V1_IDS } from '../src/content/curriculum/biochemistry';
import { auditObjective, objectivesOf, rollUp, subtopicsOf, type ObjectiveAudit } from '../src/content/curriculum/audit';
import { NUTRITION_CROSS_CUTTING } from '../src/content/curriculum/crossCutting';
import type { Coverage, Depth, Objective, OutlineRef, Subtopic } from '../src/content/curriculum/types';
import { ALL_CONCEPTS, ALL_ITEMS } from '../src/content/index';

const S = BIOCHEMISTRY;
const subtopics = subtopicsOf(S).map((x) => x.item);
const objectives = objectivesOf(S).map((x) => x.item);
const concept = new Map(ALL_CONCEPTS.map((c) => [c.id, c]));
const AUD = new Map<Objective, ObjectiveAudit>(objectives.map((o) => [o, auditObjective(o, { concepts: ALL_CONCEPTS, items: ALL_ITEMS })]));
const aud = (o: Objective) => AUD.get(o)!;
const cov = (o: Objective) => aud(o).coverage;
const covOf = (os: Objective[]) => rollUp(os.map(cov));
const itemsOf = (os: Objective[]) => new Set(os.flatMap((o) => aud(o).items.map((i) => i.id)));
const itemsFor = (ids: string[]) => new Set(ALL_ITEMS.filter((i) => i.conceptIds.some((c) => ids.includes(c))).map((i) => i.id));
const pct = (n: number, d: number) => (d ? Math.round((100 * n) / d) : 0);
const count = <T,>(xs: T[], f: (x: T) => boolean) => xs.filter(f).length;
const MARK: Record<Coverage, string> = { covered: '✅ covered', partial: '🟡 partial', missing: '⬜ missing' };
const DEPTH: Record<Depth, string> = { recognition: 'R', mechanism: 'M', application: 'A' };
const depthStr = (d: Depth[]) => d.map((x) => DEPTH[x]).join('·');
const isListed = (refs: OutlineRef[]) => refs.some((r) => r.term);
const refsOf = (s: Subtopic, o?: Objective) => [...s.outline, ...(o?.outline ?? [])];
const refStr = (r: OutlineRef) =>
  r.term
    ? `**Listed** — ${r.area} › ${r.section}${r.category ? ` › ${r.category}` : ''} › “${r.term}”`
    : `Foundational (${r.strand}) — assessed within ${r.area} › ${r.section}`;
const code = (ids: string[]) => ids.map((i) => `\`${i}\``).join(', ');
const reviewLabel = (o: Objective) => {
  const r = aud(o).review;
  return r === 'no content' ? '—' : r === 'draft' ? 'draft, not reviewed' : r;
};

const L: string[] = [];
const p = (...lines: string[]) => L.push(...lines);

// ------------------------------------------------------------------------------------------------
p(`# ${S.title}: coverage checklist and audit (version 3)`, '');
p(`Status: **${S.status}** — scope conditionally approved; content generation in progress batch by batch, each stopping for medical review. All new content is draft.`, '');
p('Generated by `npm run report:biochem` from `src/content/curriculum/`. Edit the checklist files, not this report.', '');

p('## How to read this report', '');
p('- **Hierarchy:** Subdivision → Topic → Subtopic → Assessable learning objective. Each objective has its own depth, existing content, coverage and medical review status.');
p('- **Depth codes:** R = recognition (recall or identify), M = mechanism (explain why or how), A = application (vignette, lab panel, pedigree or graph). Major topics carry all three; minor facts are recognition only and are not forced into vignettes.');
p('- **Outline basis:** *Listed* means the official USMLE Content Outline (2026) names the topic or its example; the exact area › section › category › term is quoted so it can be checked. *Foundational* means the topic is not named but belongs to a foundational strand that the 2024 outline update redistributed into organ systems (“will still be assessed within an organ system/disease process”); the section where it is assessed is given. All quoted headings and terms were verified against the published outline by `scripts/check-outline-terms.ts`.');
p('- **Coverage rule (strict):** an objective is *covered* only if existing content teaches all of it; *partial* if some of it; *missing* otherwise. A subtopic or topic is *covered* only when every objective in it is covered. Incidental mentions (for example, Down syndrome named as an Alzheimer risk factor) are recorded as mentions and never count as coverage.');
p('- **Computed coverage for new content:** content written from batch 1 onward declares the objectives it teaches, and every item declares the objective and depth it assesses. Such an objective is *covered* only when linked items assess every depth the checklist requires; otherwise it is partial. Legacy content keeps the manual judgement. “(new)” marks curriculum-linked concepts.');
p('- **Playable items:** for linked content, items are counted per objective with the depths they assess; legacy items are counted through the concepts mapped to the objective. Only complete, independently playable items count (MCQ, true/false, crossword clue, Mechanism Lab, Match Up, complete Connections puzzle, Mystery Patient case). Connections category-bank entries are builder input and are excluded from counts and from coverage evidence.');
p('- **Coverage is not clinical validation:** an objective marked covered has linked draft content at every required depth. It says nothing about medical accuracy; that requires medical review.');
p('- **Medical review:** the least advanced review status of the mapped content. “—” means no content exists yet.');
p('- **Cross-links:** where another subject owns the clinical detail (for example, hemochromatosis in Gastrointestinal), the objective is marked with its home subject and Biochemistry teaches only the biochemical or genetic part, so knowledge is not duplicated.');
p('- **Copyright:** the owner uses First Aid 2026 privately to check scope. No text, tables, mnemonics, illustrations or questions from it or any other commercial resource are reproduced here.', '');

// ------------------------------------------------------------------------------------------------
const subCov = subtopics.map((s) => covOf(s.objectives));
const objCov = (c: Coverage) => count(objectives, (o) => cov(o) === c);
const subtopicOf = (o: Objective) => subtopics.find((s) => s.objectives.includes(o))!;
const listedObjectives = count(objectives, (o) => isListed(refsOf(subtopicOf(o), o)));
const allThree = count(objectives, (o) => o.depth.length === 3);
const mappedConcepts = [...new Set(objectives.flatMap((o) => aud(o).concepts))].sort();
const linkedObjectives = objectives.filter((o) => aud(o).basis === 'linked content');
const mentioned = [...new Set(objectives.flatMap((o) => o.mentions))].filter((id) => !mappedConcepts.includes(id)).sort();
const allItems = itemsOf(objectives);

p('## Summary', '');
p('| Measure | Value |', '|---|---|');
p(`| Subdivisions / topics / subtopics | ${S.subdivisions.length} / ${S.subdivisions.reduce((n, d) => n + d.topics.length, 0)} / ${subtopics.length} |`);
p(`| Assessable learning objectives | ${objectives.length} |`);
p(`| Disorder objectives with an integration chain | ${count(objectives, (o) => o.kind === 'disorder')} |`);
p(`| Objectives covered / partial / missing | ${objCov('covered')} (${pct(objCov('covered'), objectives.length)}%) / ${objCov('partial')} (${pct(objCov('partial'), objectives.length)}%) / ${objCov('missing')} (${pct(objCov('missing'), objectives.length)}%) |`);
p(`| Subtopics covered / partial / missing | ${count(subCov, (c) => c === 'covered')} / ${count(subCov, (c) => c === 'partial')} / ${count(subCov, (c) => c === 'missing')} |`);
p(`| Objectives tied to a listed outline term / foundational only | ${listedObjectives} / ${objectives.length - listedObjectives} |`);
p(`| Depth: objectives requiring R / M / A | ${count(objectives, (o) => o.depth.includes('recognition'))} / ${count(objectives, (o) => o.depth.includes('mechanism'))} / ${count(objectives, (o) => o.depth.includes('application'))} |`);
p(`| Objectives requiring all three depths | ${allThree} |`);
p(`| Subtopic priority: core / important / supporting | ${count(subtopics, (s) => s.priority === 3)} / ${count(subtopics, (s) => s.priority === 2)} / ${count(subtopics, (s) => s.priority === 1)} |`);
p(`| Objectives whose clinical detail is owned by another subject | ${count(objectives, (o) => !!o.home)} |`);
p(`| Existing content concepts teaching an objective | ${mappedConcepts.length} |`);
p(`| Playable items assessing these objectives (Connections category-bank entries excluded) | ${allItems.size} |`);
p(`| Objectives covered by curriculum-linked new content (computed) | ${count(linkedObjectives, (o) => cov(o) === 'covered')} of ${linkedObjectives.length} linked |`);
p('| Content medically reviewed or approved | 0 (all existing content is draft, AI-drafted) |', '');

p('### By subdivision', '');
p('| Subdivision | Topics | Subtopics | Objectives | Covered | Partial | Missing | Items available |', '|---|---|---|---|---|---|---|---|');
for (const d of S.subdivisions) {
  const sts = d.topics.flatMap((t) => t.subtopics);
  const obs = sts.flatMap((s) => s.objectives);
  p(`| ${d.title} | ${d.topics.length} | ${sts.length} | ${obs.length} | ${count(obs, (o) => cov(o) === 'covered')} | ${count(obs, (o) => cov(o) === 'partial')} | ${count(obs, (o) => cov(o) === 'missing')} | ${itemsOf(obs).size} |`);
}
p('');

// ------------------------------------------------------------------------------------------------
p('## Changes in version 3 (owner review of version 2)', '');
p('- Enzyme inhibition: pure noncompetitive and irreversible inhibition are now separate objectives; uncompetitive and mixed inhibition added with their Km, Vmax and Lineweaver–Burk effects.');
p('- Fabry disease described as X-linked with frequently affected heterozygous females (checklist, legacy concept, X-linked connection group).');
p('- Sorbitol pathway reframed as one contributor to diabetic complications alongside glycation, PKC activation, hexosamine flux and oxidative stress; sorbitol is most important in the lens.');
p('- Mechanism review: hyperammonemia (α-ketoglutarate depletion marked as debated), kwashiorkor edema (multifactorial), von Gierke and hereditary fructose intolerance hyperuricemia, alcoholic ketoacidosis, homocystinuria lens mechanism, familial chylomicronemia atherosclerosis risk, ADA toxicity, Marfan TGF-β wording, thiamine–glucose rationale.');
p('- Nutrition kept as a cross-cutting area for later subjects (see the section below).');
p('- Batch 1 content added for 25 Molecular biochemistry objectives and Batch 2 for the remaining 26, so all 51 Molecular objectives now have linked content; coverage for them is computed from the content. All of it is draft and not medically reviewed.', '');

p('## Changes from version 1', '');
const added = subtopics.filter((s) => s.origin.length === 0);
const split = subtopics.filter((s) => s.origin.length && !(s.origin.length === 1 && s.origin[0] === s.id));
p(`- All ${BIOCHEMISTRY_V1_IDS.length} first-version checklist concepts are kept and traced (test-enforced). Each is now a subtopic divided into independently assessable objectives.`);
p(`- Split into individual subtopics: ${split.map((s) => `${s.title} (from ${code(s.origin)})`).join('; ')}.`);
p(`- New subtopics: ${added.map((s) => s.title).join('; ')}.`);
p('- Grouped entries (glycogen storage, lysosomal storage, autosomal dominant, autosomal recessive and X-linked disorders, trinucleotide repeats, vitamins) now have one objective per disease or vitamin.');
p('- Coverage reclassified under the strict rule. Collagen disorders and X-linked recessive disorders were “covered” in version 1; they are now partial because mandatory points are missing (collagen types II and IV, EDS subtypes, Marfan valve disease; Wiskott–Aldrich, Hunter, ocular albinism).');
p('- Down syndrome: the Alzheimer concept’s reference to Down syndrome is now recorded as a mention only. Down syndrome objectives are missing.');
p('- Scientific corrections: DNA repair separates ATM (a DNA damage response kinase; ataxia–telangiectasia), nonhomologous end joining (SCID with radiosensitivity) and Fanconi anemia (interstrand crosslink repair). Also clarified: metformin’s complex I action is debated; fragile X is X-linked with reduced penetrance in females; homocystinuria has four causes; PDH deficiency is most often X-linked; vitamin K deficiency prolongs PT first with a normal platelet count.');
p('- Every outline mapping now quotes the exact section, category and listed term, and separates listed from foundational objectives.', '');

// ------------------------------------------------------------------------------------------------
p('## Checklist and audit', '');
for (const d of S.subdivisions) {
  p(`### ${d.title}`, '', `_Scope:_ ${d.scope}`, '');
  for (const t of d.topics) {
    const obs = t.subtopics.flatMap((s) => s.objectives);
    const ids = [...new Set(obs.flatMap((o) => aud(o).concepts))];
    const reviews = [...new Set(obs.map(reviewLabel).filter((r) => r !== '—'))];
    p(`#### ${t.title} — ${MARK[covOf(obs)]}`, '');
    p(`- Objectives: ${obs.length} (${count(obs, (o) => cov(o) === 'covered')} covered, ${count(obs, (o) => cov(o) === 'partial')} partial, ${count(obs, (o) => cov(o) === 'missing')} missing); ${count(obs, (o) => cov(o) !== 'covered')} still need content.`);
    p(`- Existing content: ${ids.length ? code(ids) : 'none'}.`);
    p(`- Playable items available: ${itemsOf(obs).size}.`);
    p(`- Medical review status: ${reviews.length ? reviews.join(', ') : 'no content to review'}.`, '');
    for (const s of t.subtopics) {
      const origin = s.origin.length === 0 ? ' · new' : s.origin[0] !== s.id ? ` · from ${code(s.origin)}` : '';
      p(`**${s.title}** — ${MARK[covOf(s.objectives)]} · priority ${s.priority} · \`${s.id}\`${origin}`, '');
      for (const r of s.outline) p(`- ${refStr(r)}`);
      if (s.crossLinks.length) p(`- Cross-links: ${s.crossLinks.map((c) => `${c.subject} (${c.owns})`).join('; ')}`);
      p('');
      p('| Objective | Depth | Basis | Existing content | Items (depths assessed) | Coverage | Medical review |', '|---|---|---|---|---|---|---|');
      for (const o of s.objectives) {
        const extra = o.outline.length ? `<br>_${o.outline.map((r) => (r.term ? `listed: “${r.term}” (${r.section})` : `foundational: ${r.section}`)).join('; ')}_` : '';
        const home = o.home ? `<br>_clinical detail: ${o.home}_` : '';
        const a = aud(o);
        const note = a.note ? `<br>_${a.note}_` : '';
        const ment = o.mentions.length ? `<br>_mentions only: ${code(o.mentions)}_` : '';
        const basis = isListed(refsOf(s, o)) ? 'Listed' : 'Foundational';
        const conceptsCell = a.concepts.length ? a.concepts.map((id) => (a.linked.includes(id) ? `\`${id}\` (new)` : `\`${id}\``)).join(', ') : '—';
        const itemsCell = a.items.length ? `${a.items.length}${a.depthsAssessed.length ? ` (${depthStr(a.depthsAssessed)})` : ' (legacy)'}` : '—';
        p(`| ${o.text}${extra}${home} | ${depthStr(o.depth)} | ${basis} | ${conceptsCell}${ment} | ${itemsCell} | ${MARK[a.coverage]}${note} | ${reviewLabel(o)} |`);
      }
      const chains = s.objectives.filter((o) => o.integration);
      if (chains.length) {
        p('', '<details><summary>Integration chains (blocked step → accumulates → decreased → physiology → findings)</summary>', '');
        for (const o of chains) {
          const i = o.integration!;
          p(`- **${o.text}** Block: ${i.block}. ↑ ${i.accumulates.join('; ') || '—'}. ↓ ${i.decreased.join('; ') || '—'}. Physiology: ${i.physiology.join('; ')}. Findings: ${i.findings.join('; ')}.`);
        }
        p('', '</details>');
      }
      p('');
    }
  }
}

// ------------------------------------------------------------------------------------------------
p('## Existing content mapped to this checklist', '');
p('| Content concept | Title | Items | Review status | Objectives it teaches |', '|---|---|---|---|---|');
for (const id of mappedConcepts) {
  const c = concept.get(id)!;
  p(`| \`${id}\`${c.curriculum ? ' (new)' : ''} | ${c.title} | ${itemsFor([id]).size} | ${c.review.status} (${c.review.provenance}) | ${count(objectives, (o) => aud(o).concepts.includes(id))} |`);
}
p('');
p(`Mentioned only (not counted as coverage): ${code(mentioned)}.`, '');

p('## Cross-links to later subjects', '');
const bySubject = new Map<string, number>();
for (const o of objectives) if (o.home) bySubject.set(o.home, (bySubject.get(o.home) ?? 0) + 1);
p('| Subject | Objectives whose clinical detail it owns |', '|---|---|');
for (const [k, v] of [...bySubject].sort((a, b) => b[1] - a[1])) p(`| ${k} | ${v} |`);
p('');

p('## Suggested build order (after approval)', '');
p('Core subtopics first, then those with the largest share of objectives still needing content; batches of about 25–50 objectives.', '');
const order = subtopics
  .map((s) => ({ s, gap: count(s.objectives, (o) => cov(o) !== 'covered') }))
  .filter((x) => x.gap > 0)
  .sort((a, b) => b.s.priority - a.s.priority || b.gap / b.s.objectives.length - a.gap / a.s.objectives.length);
order.forEach(({ s, gap }, i) => p(`${i + 1}. ${s.title} — ${gap} of ${s.objectives.length} objectives need content (priority ${s.priority})`));
p('');

p('## Nutrition as a cross-cutting area', '');
p('Nutrition is a listed outline section with a stated recent emphasis, so each later organ-system subject must link back to these Nutrition objectives (as cross-links or application objectives) instead of re-teaching them. Source: `src/content/curriculum/crossCutting.ts` (test-enforced).', '');
p('| Later subject | Nutrition objectives to integrate |', '|---|---|');
for (const [k, v] of Object.entries(NUTRITION_CROSS_CUTTING)) p(`| ${k} | ${v.map((id) => `\`${id}\``).join(', ')} |`);
p('');

p('## Not in this checklist (owned by later subjects)', '');
p('- Heme synthesis and porphyrias, hemoglobin structure, iron deficiency and overload as diseases: Hematology and Oncology.');
p('- Pharmacokinetics and drug metabolism: Pharmacology (enzyme kinetics and inhibition are now in Biochemistry).');
p('- Steroid and thyroid hormone synthesis, congenital adrenal hyperplasia (`cah-21`): Endocrine.');
p('- Hemochromatosis and Wilson disease clinical detail, alcohol-associated liver disease: Gastrointestinal.', '');

p('## Content requiring review', '');
p('- All existing content is `draft` / AI-drafted; none is medically reviewed or approved, and none is shown in a production build.');
p('- Each coverage judgement should be confirmed by the medical reviewer when the mapped concept is reviewed.');
p('- Pre-strategy batches (neurology and behavioral, musculoskeletal and skin, reproductive and endocrine) are preserved unchanged for their own subject audits.');
p('- QA finding for a later correction pass: `mskSkin.ts` uses British spellings (mineralisation, favour, behaviour) where the app standard is American spelling.', '');

writeFileSync('docs/subjects/BIOCHEMISTRY_COVERAGE.md', L.join('\n'));
console.log(`subtopics ${subtopics.length}, objectives ${objectives.length}, covered ${objCov('covered')}, partial ${objCov('partial')}, missing ${objCov('missing')}, listed ${listedObjectives}, mapped ${mappedConcepts.length}, items ${allItems.size}`);
