/**
 * Writes the coverage audit report for a subject checklist.
 * Usage: npx vite-node scripts/curriculum-report.ts  (or npm run report:biochem)
 */
import { writeFileSync } from 'node:fs';
import { BIOCHEMISTRY, checklistConcepts } from '../src/content/curriculum/biochemistry';
import type { ChecklistConcept } from '../src/content/curriculum/types';
import { ALL_CONCEPTS, ALL_ITEMS } from '../src/content/index';

const s = BIOCHEMISTRY;
const all = checklistConcepts(s);
const count = <T extends string>(xs: ChecklistConcept[], key: (c: ChecklistConcept) => T) =>
  xs.reduce<Record<string, number>>((m, c) => ((m[key(c)] = (m[key(c)] ?? 0) + 1), m), {});
const pct = (n: number, d: number) => (d ? Math.round((100 * n) / d) : 0);
const cov = count(all, (c) => c.coverage);
const depth = count(all, (c) => c.depth);
const prio = count(all, (c) => String(c.priority));
const mapped = [...new Set(all.flatMap((c) => c.existing))].sort();
const byId = new Map(ALL_CONCEPTS.map((c) => [c.id, c]));
const itemsFor = (id: string) => ALL_ITEMS.filter((i) => i.conceptIds.includes(id)).length;
const mark = { covered: '✅ covered', partial: '🟡 partial', missing: '⬜ missing' } as const;

const L: string[] = [];
L.push(`# ${s.title}: coverage checklist and audit`, '');
L.push(`Status: **${s.status}** — awaiting owner approval. No new content has been generated against this checklist.`, '');
L.push('Generated by `npm run report:biochem` from `src/content/curriculum/`. Edit the checklist files, not this report.', '');
L.push('## How this checklist was built', '');
L.push('- **Authority:** the official USMLE Content Outline (2026). Every checklist concept links to one or more outline sections; `listed` means the outline names the topic or its example group, `foundational` means it is basic science the outline distributes across systems.');
L.push('- **Coverage reference:** the owner holds First Aid 2026 as a private editorial reference. I do not have access to it, so this checklist was written from the outline and standard Step 1 biochemistry knowledge. Subdivision names follow the owner\'s plan; no First Aid text, tables, mnemonics or structure below subdivision level is reproduced. **The owner should cross-check the checklist against First Aid privately and tell me what is missing or over-scoped.**');
L.push('- **Depth:** recall (recognize), understand (explain mechanism), apply (use in a clinical vignette). Step 2/3 management is excluded.');
L.push('- **Coverage judgement** of existing content was made by reading each existing concept, not automatically. "Covered" means the must-know points are addressed by an existing concept; it does **not** mean medically reviewed.', '');
L.push('## Summary', '');
L.push(`| Measure | Value |`, `|---|---|`);
L.push(`| Subdivisions | ${s.subdivisions.length} |`);
L.push(`| Topics | ${s.subdivisions.reduce((n, d) => n + d.topics.length, 0)} |`);
L.push(`| Checklist concepts | ${all.length} |`);
L.push(`| Must-know points | ${all.reduce((n, c) => n + c.must.length, 0)} |`);
L.push(`| Covered | ${cov.covered ?? 0} (${pct(cov.covered ?? 0, all.length)}%) |`);
L.push(`| Partial | ${cov.partial ?? 0} (${pct(cov.partial ?? 0, all.length)}%) |`);
L.push(`| Missing | ${cov.missing ?? 0} (${pct(cov.missing ?? 0, all.length)}%) |`);
L.push(`| Depth: recall / understand / apply | ${depth.recall ?? 0} / ${depth.understand ?? 0} / ${depth.apply ?? 0} |`);
L.push(`| Priority: core (3) / important (2) / supporting (1) | ${prio['3'] ?? 0} / ${prio['2'] ?? 0} / ${prio['1'] ?? 0} |`);
L.push(`| Existing content concepts mapped | ${mapped.length} |`);
L.push(`| Existing concepts medically reviewed / approved | 0 |`, '');
L.push('## By subdivision', '');
L.push('| Subdivision | Concepts | Covered | Partial | Missing | Core |', '|---|---|---|---|---|---|');
for (const d of s.subdivisions) {
  const cs = d.topics.flatMap((t) => t.concepts);
  const k = count(cs, (c) => c.coverage);
  L.push(`| ${d.title} | ${cs.length} | ${k.covered ?? 0} | ${k.partial ?? 0} | ${k.missing ?? 0} | ${cs.filter((c) => c.priority === 3).length} |`);
}
L.push('');
L.push('## Checklist', '');
for (const d of s.subdivisions) {
  L.push(`### ${d.title}`, '', `_Scope:_ ${d.scope}`, '');
  for (const t of d.topics) {
    L.push(`#### ${t.title}`, '');
    for (const c of t.concepts) {
      const outline = [...new Set(c.outline.map((o) => `${o.area} › ${o.section}${o.listed ? '' : ' (foundational)'}`))].join('; ');
      L.push(`- **${c.title}** — ${mark[c.coverage]} · ${c.depth} · priority ${c.priority} · \`${c.id}\``);
      L.push(`  - Outline: ${outline}`);
      L.push(`  - Elements: ${c.elements.join(', ')}`);
      L.push(`  - Must know:`);
      for (const m of c.must) L.push(`    - ${m}`);
      if (c.existing.length) L.push(`  - Existing content: ${c.existing.map((id) => `\`${id}\``).join(', ')}`);
      if (c.gap) L.push(`  - Gap: ${c.gap}`);
    }
    L.push('');
  }
}
L.push('## Existing content mapped to this checklist', '');
L.push('| Concept | Title | Items | Review status | Used by checklist concepts |', '|---|---|---|---|---|');
for (const id of mapped) {
  const e = byId.get(id)!;
  const users = all.filter((c) => c.existing.includes(id)).map((c) => `\`${c.id}\``).join(', ');
  L.push(`| \`${id}\` | ${e.title} | ${itemsFor(id)} | ${e.review.status} (${e.review.provenance}) | ${users} |`);
}
L.push('');
L.push('## Gaps in suggested build order (priority, then missing before partial)', '');
const rank = (c: ChecklistConcept) => (c.coverage === 'missing' ? 0 : 1);
const gaps = all.filter((c) => c.coverage !== 'covered').sort((a, b) => b.priority - a.priority || rank(a) - rank(b) || all.indexOf(a) - all.indexOf(b));
gaps.forEach((c, i) => L.push(`${i + 1}. ${c.title} — ${c.coverage}, priority ${c.priority}`));
L.push('');
L.push('## Not in this checklist (assigned to later subjects)', '');
L.push('- Heme synthesis, porphyrias, iron and hemoglobin: Hematology and Oncology.');
L.push('- Enzyme kinetics, pharmacokinetics and drug metabolism: Pharmacology.');
L.push('- Steroid hormone synthesis and congenital adrenal hyperplasia (`cah-21`), thyroid hormone synthesis: Endocrine.');
L.push('- Copper (Wilson disease, Menkes beyond collagen cross-linking), iron overload (hemochromatosis): Gastrointestinal and Hematology.');
L.push('- Immunodeficiency mechanisms beyond ADA deficiency and Bruton: Immunology.', '');
L.push('## Content requiring review', '');
L.push('- **All** existing content is `draft` / `ai-drafted`; none is medically reviewed or approved, and none is shown in a production build.');
L.push('- Coverage judgements above should be confirmed by the medical reviewer when each existing concept is reviewed.');
L.push('- Pre-strategy batches (neurology and behavioral, musculoskeletal and skin, reproductive and endocrine) are preserved unchanged for their own subject audits; only the parts that touch Biochemistry are mapped here.');
L.push('- QA finding for a later correction pass: `mskSkin.ts` uses British spellings (mineralisation, favour, behaviour) where the app standard is American spelling.');
L.push('- Down syndrome is not a concept; it appears only as an Alzheimer risk factor (`alzheimer`).', '');
writeFileSync('docs/subjects/BIOCHEMISTRY_COVERAGE.md', L.join('\n'));
console.log(`wrote ${all.length} concepts; coverage`, cov, 'depth', depth, 'priority', prio, 'mapped', mapped.length);
